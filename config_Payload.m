
function struct_out = config_Payload()
    % CONFIG_FEM_TEMPLATE Generates a FEM structural template.
    %
    % This function outputs a struct formatted for the 'fem' class methods.
    % It contains two primary sub-arrays: .nodes and .elements.
    % Use this file as a reference or copy it to create new substructures.
    % If copying, rename 'config_fem_template' to 'config_[desired
    % structure name]' in the function line and the file name.
    
    struct_out = struct();
    
    %% =====================================================================
    %  NODE DEFINITIONS
    %  =====================================================================
    %  Each node requires the following fields:
    %  - id          : [String] Unique identifier for the node.
    %  - x, y        : [Double] Spatial coordinates in meters (m).
    %  - mass        : [Double] Point translational mass in kg.
    %  - inertia     : [Double] Point rotational mass moment of inertia in kg*m^2.
    %  - constraints : [1x3 Array] Boundary conditions for [x, y, theta].
    %                  0 = Free to move.
    %                  1 = Fixed / Grounded to the "universe".
    %  - k_rot       : [Double] Rotational stiffness in N*m/rad. Used to ground 
    %                  rotational DOFs (e.g., modeling an ACS or preventing 
    %                  singular matrices on pin joints).
    
    % Nodes for Secondary Mirror Boom: SecMirBm
    m_SecMirBm_node = 1; I_SecMirBm_node = 1;
       struct_out.nodes(1) = struct(...
        'id', "SecMirBm Bot. Left", ...
        'x', -5, 'y', 4.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(2) = struct(...
        'id', "SecMirBm Mid. left", ...
        'x', -3.5, 'y', 11.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(3) = struct(...
        'id', "SecMirBm Top left", ...
        'x', -2, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(4) = struct(...
        'id', "SecMirBm Mid. Top", ...
        'x', 0, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(5) = struct(...
        'id', "SecMirBm Top Right", ...
        'x', 2, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(6) = struct(...
        'id', "SecMirBm Mid. Right", ...
        'x', 3.5, 'y', 11.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 
    
       struct_out.nodes(7) = struct(...
        'id', "SecMirBm Bot. Right", ...
        'x', 5, 'y', 4.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

    % Node for Secondary Mirror: SecMir
    m_SecMir_node = 1; I_SecMir_node = 1;
       struct_out.nodes(8) = struct(...
        'id', "SecondaryMirror", ...
        'x', 0, 'y', 17, ...
        'mass', m_SecMir_node, ...
        'inertia', I_SecMir_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 
  
        
        
    %% =====================================================================
    %  ELEMENT DEFINITIONS
    %  =====================================================================
    %  Each element requires the following fields:
    %  - id          : [String] Unique identifier for the element.
    %  - type        : [String] Element formulation type. 
    %                  Currently supported: "beam"
    %                  Future support   : "spring", "isolator"
    %  - nodes       : [1x2 String Array] Exact IDs of the connecting nodes.
    %  - E           : [Double] Young's Modulus in Pascals (Pa).
    %  - I           : [Double] Area Moment of Inertia in m^4.
    %  - A           : [Double] Cross-sectional area in m^2.
    %  - rho         : [Double] Mass density per unit length in kg/m.
    %  - k_discrete  : [Double] Stiffness in N/m (Used for discrete spring 
    %                  elements, ignored if type == "beam").
    
    % Elements: Secondary Mirror Boom: SecMirBm
    E_SecMirBm = 70e9; I_SecMirBm = 0.09; A_SecMirBm = 20; rho_SecMirBm = 2700;
    struct_out.elements(1) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Bot. Left", "SecMirBm Mid. Left"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

     struct_out.elements(2) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Left", "SecMirBm Top Left"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

     struct_out.elements(3) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Top Left", "SecMirBm Mid. Top"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

     struct_out.elements(4) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Top", "SecMirBm Top Right"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

     struct_out.elements(5) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Top Right", "SecMirBm Mid. Right"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

     struct_out.elements(6) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Right", "SecMirBm Bot. Right"], ... 
        'E', E_SecMirBm, ...                       
        'I', I_SecMirBm, ...
        'A', A_SecMirBm, ...
        'rho', rho_SecMirBm, ...                        
        'k_discrete', 0);

    % Element: Secondary Mirror: SecMir
    E_SecMir = 70e9; I_SecMir = 0.07; A_SecMir = 0.375; rho_SecMir = 2700;
    struct_out.elements(1) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Top", "SecondaryMirror"], ... 
        'E', E_SecMir, ...                       
        'I', I_SecMir, ...
        'A', A_SecMir, ...
        'rho', rho_SecMir, ...                        
        'k_discrete', 0);


end