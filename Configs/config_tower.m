function struct_out = config_tower()
    struct_out = struct();
    
    % Define Nodes using string IDs
    % Central base is at (0,0), nodes are at x = -1 and x = 1. Top node is at y = 2.
    struct_out.nodes(1) = struct('id', "Bottom Joint", 'x', 0,  'y', 2, ...
        'mass', 100, 'inertia', 200, ...
        'constraints', [0, 0, 0], 'k_rot', 10); % Free
    struct_out.nodes(2) = struct('id', "Middle Joint", 'x', 0,  'y', 3, ...
        'mass', 10, 'inertia', 20, ...
        'constraints', [0, 0, 0], 'k_rot', 10); % Free
    struct_out.nodes(3) = struct('id', "Top Joint", 'x', 0,  'y', 4, ...
        'mass', 10, 'inertia', 20, ...
        'constraints', [0, 0, 0], 'k_rot', 10); % Free
    
    % Define Elements
    struct_out.elements(1) = struct(...
        'id', "Lower Beam", ...
        'type', "beam", ...
        'nodes', ["Bottom Joint", "Middle Joint"], ...
        'E', 70e9, 'I', 1e-4, 'A', 0.01, ...
        'rho', 1, ...
        'k_discrete', 0);
    
    struct_out.elements(2) = struct(...
        'id', "Upper Beam", ...
        'type', "beam", ...
        'nodes', ["Middle Joint", "Top Joint"], ...
        'E', 70e9, 'I', 1e-4, 'A', 0.01, ...
        'rho', 1, ...
        'k_discrete', 0);