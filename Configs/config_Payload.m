
function struct_out = config_Payload()
    % CONFIG_FEM_TEMPLATE Generates a FEM structural template.
    %
    % This function outputs a struct formatted for the 'fem' class methods.
    % It contains two primary sub-arrays: .nodes and .elements.
    % Use this file as a reference or copy it to create new substructures.
    % If copying, rename 'config_fem_template' to 'config_[desired
    % structure name]' in the function line and the file name.
    
    struct_out = struct();
    
    %% =====================================================================
    %  NODE DEFINITIONS
    %  =====================================================================
    %  Each node requires the following fields:
    %  - id          : [String] Unique identifier for the node.
    %  - x, y        : [Double] Spatial coordinates in meters (m).
    %  - mass        : [Double] Point translational mass in kg.
    %  - inertia     : [Double] Point rotational mass moment of inertia in kg*m^2.
    %  - constraints : [1x3 Array] Boundary conditions for [x, y, theta].
    %                  0 = Free to move.
    %                  1 = Fixed / Grounded to the "universe".
    %  - k_rot       : [Double] Rotational stiffness in N*m/rad. Used to ground 
    %                  rotational DOFs (e.g., modeling an ACS or preventing 
    %                  singular matrices on pin joints).
    
    % Nodes for Secondary Mirror Boom: SecMirBm
    m_SecMirBm_node = 0; I_SecMirBm_node = 0;
       struct_out.nodes(1) = struct(...
        'id', "SecMirBm Bot. Left", ...
        'x', -5, 'y', 4.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(2) = struct(...
        'id', "SecMirBm Mid. Left", ...
        'x', -3.5, 'y', 11.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(3) = struct(...
        'id', "SecMirBm Top Left", ...
        'x', -2, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(4) = struct(...
        'id', "SecMirBm Mid. Top", ...
        'x', 0, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(5) = struct(...
        'id', "SecMirBm Top Right", ...
        'x', 2, 'y', 18.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

       struct_out.nodes(6) = struct(...
        'id', "SecMirBm Mid. Right", ...
        'x', 3.5, 'y', 11.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 
    
       struct_out.nodes(7) = struct(...
        'id', "SecMirBm Bot. Right", ...
        'x', 5, 'y', 4.5, ...
        'mass', m_SecMirBm_node, ...
        'inertia', I_SecMirBm_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 

    % Node for Secondary Mirror: SecMir
    % Mass for secondary mirror set to 8 kg for testing
    % Intertia found by using plate equation (w = .5m, h = .5m)
    m_SecMir_node = 8 ; I_SecMir_node = 0.3333;
       struct_out.nodes(8) = struct(...
        'id', "SecondaryMirror", ...
        'x', 0, 'y', 17, ...
        'mass', m_SecMir_node, ...
        'inertia', I_SecMir_node, ...
        'constraints', [0, 0, 0], ... % Fixed in X, Y, and Theta
        'k_rot', 0); 
  
        
        
    %% =====================================================================
    %  ELEMENT DEFINITIONS
    %  =====================================================================
    %  Each element requires the following fields:
    %  - id          : [String] Unique identifier for the element.
    %  - type        : [String] Element formulation type. 
    %                  Currently supported: "beam"
    %                  Future support   : "spring", "isolator"
    %  - nodes       : [1x2 String Array] Exact IDs of the connecting nodes.
    %  - E           : [Double] Young's Modulus in Pascals (Pa).
    %  - I           : [Double] Area Moment of Inertia in m^4.
    %  - A           : [Double] Cross-sectional area in m^2.
    %  - rho         : [Double] Mass density per unit length in kg/m.
    %  - k_spring    : [1x3 Array] Local stiffness for spring elements [N/m, N/m, N*m/rad].
    %                  Format: [k_axial, k_shear, k_torsion].

    % 1900 kg/m^3 density for Carbon fiber 
    % 0.08532 m^3 total volume for hollow tubes
    % Secondary Mirror Boom Weight Calulated to be 162.116 kg 
    % Total inertia Cal'd at 6.42012 kg-m^2 
    
    % Elements: Secondary Mirror Boom: SecMirBm (SIDES)
    % Young's Modulus found for a high stiffness grade carbon fiber 
    % Inertia cal'd here for the side elements ONLY given difference in length
    % Cross-sectional annulus area found for hollow tube (r2 = 0.2m, r1 = 0.198m)
    % Mass density per unit length found using MD = 1900 kg/m^3 * 0.0025 m^2
    E_SecMirBmsd = 4e11; I_SecMirBmsd = 1.36983; A_SecMirBmsd = 0.0025; rho_SecMirBmsd = 4.75;
    struct_out.elements(1) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Bot. Left", "SecMirBm Mid. Left"], ... 
        'E', E_SecMirBmsd, ...                       
        'I', I_SecMirBmsd, ...
        'A', A_SecMirBmsd, ...
        'rho', rho_SecMirBmsd, ...                        
        'k_spring', [0, 0, 0]);

     struct_out.elements(2) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Left", "SecMirBm Top Left"], ... 
        'E', E_SecMirBmsd, ...                       
        'I', I_SecMirBmsd, ...
        'A', A_SecMirBmsd, ...
        'rho', rho_SecMirBmsd, ...                        
        'k_spring', [0, 0, 0]);

     struct_out.elements(5) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Top Right", "SecMirBm Mid. Right"], ... 
        'E', E_SecMirBmsd, ...                       
        'I', I_SecMirBmsd, ...
        'A', A_SecMirBmsd, ...
        'rho', rho_SecMirBmsd, ...                        
        'k_spring', [0, 0, 0]);

     struct_out.elements(6) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Right", "SecMirBm Bot. Right"], ... 
        'E', E_SecMirBmsd, ...                       
        'I', I_SecMirBmsd, ...
        'A', A_SecMirBmsd, ...
        'rho', rho_SecMirBmsd, ...                        
        'k_spring', [0, 0, 0]);

    % Elements: Secondary Mirror Boom: SecMirBm (TOP)
    % Inertia cal'd here for the top elements ONLY given difference in length
    % All other properties stay consistent with side elements of boom
    % Leaving variables as is just in case things change
     E_SecMirBmtp = E_SecMirBmsd ; I_SecMirBmtp = 0.37633; A_SecMirBmtp = A_SecMirBmsd; rho_SecMirBmtp = rho_SecMirBmsd;
     struct_out.elements(3) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Top Left", "SecMirBm Mid. Top"], ... 
        'E', E_SecMirBmtp, ...                       
        'I', I_SecMirBmtp, ...
        'A', A_SecMirBmtp, ...
        'rho', rho_SecMirBmtp, ...                        
        'k_spring', [0, 0, 0]);

     struct_out.elements(4) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Top", "SecMirBm Top Right"], ... 
        'E', E_SecMirBmtp, ...                       
        'I', I_SecMirBmtp, ...
        'A', A_SecMirBmtp, ...
        'rho', rho_SecMirBm, ...                        
        'k_spring', [0, 0, 0]);

    % Element: Secondary Mirror: SecMir
    % Inertia cal'd here for the SecMir element ONLY given difference in length
    % All other properties stay consistent with side elements of boom
    % Leaving variables as is just in case things change
    E_SecMir = E_SecMirBmsd; I_SecMir = 0.094; A_SecMir = A_SecMirBmsd; rho_SecMir = rho_SecMirBmsd;
    struct_out.elements(7) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["SecMirBm Mid. Top", "SecondaryMirror"], ... 
        'E', E_SecMir, ...                       
        'I', I_SecMir, ...
        'A', A_SecMir, ...
        'rho', rho_SecMir, ...                        
        'k_spring', [0, 0, 0]);


end
