function struct_out = config_base_support()
struct_out = struct();

    % Define Nodes using string IDs
    % Central base is at (0,0), nodes are at x = -1 and x = 1. Top node is at y = 2.
    struct_out.nodes(1) = struct(...
        'id', "Bottom Left", 'x', -1, 'y', 0, ...
        'mass', 10, 'inertia', 20, ...
        'constraints', [1, 1, 1], 'k_rot', 0); % Pinned/Fixed
    struct_out.nodes(2) = struct(...
        'id', "Top", 'x', 0,  'y', 2, ...
        'mass', 100, 'inertia', 200, ...
        'constraints', [0, 0, 0], 'k_rot', 10); % Free with a rotational spring modeling the attachment
    struct_out.nodes(3) = struct(...
        'id', "Bottom Right", 'x', 1,  'y', 0, ...
        'mass', 10, 'inertia', 20, ...
        'constraints', [1, 1, 0], 'k_rot', 0); % Pinned but can rotate
    
    % Define Elements
    struct_out.elements(1) = struct(...
        'id', "Beam Left", ...
        'type', "beam", ...
        'nodes', ["Bottom Left", "Top"], ...
        'E', 70e9, 'I', 1e-4, 'A', 0.01, ...
        'rho', 1, ...
        'k_discrete', 0);
    
    struct_out.elements(2) = struct(...
        'id', "Beam Right", ...
        'type', "beam", ...
        'nodes', ["Top", "Bottom Right"], ...
        'E', 70e9, 'I', 1e-4, 'A', 0.01, ...
        'rho', 2, ...
        'k_discrete', 0);
    
    struct_out.elements(3) = struct(...
        'id', "Beam Base", ...
        'type', "beam", ...
        'nodes', ["Bottom Right", "Bottom Left"], ...
        'E', 70e9, 'I', 1e-4, 'A', 0.01, ...
        'rho', 3, ... 
        'k_discrete', 0);
end