        'constraints', [0, 0, 0], 'k_rot', 0);

    struct_out.nodes(3) = struct(...
        'id', "Obench PM base Middle left", ...
        'x', -1.5, 'y', 4.5, ...
        'mass', m_Obench_node, 'inertia', I_Obench_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

    struct_out.nodes(4) = struct(...
        'id', "Obench Camera base", ...
        'x', 0, 'y', 4.5, ...
        'mass', m_Obench_node, 'inertia', I_Obench_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

     struct_out.nodes(5) = struct(...
        'id', "Obench PM base Middle Right", ...
        'x', 1.5, 'y', 4.5, ...
        'mass', m_Obench_node, 'inertia', I_Obench_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

      struct_out.nodes(6) = struct(...
        'id', "Obench PM Base Right", ...
        'x', 3, 'y', 4.5, ...
        'mass', m_Obench_node, 'inertia', I_Obench_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

       struct_out.nodes(7) = struct(...
        'id', "Obench Far Right", ...
        'x', 5, 'y', 4.5, ...
        'mass', m_Obench_node, 'inertia', I_Obench_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

% Nodes: Primary Mirrors: PM
m_PM_node = 1; I_PM_node = 1;
    struct_out.nodes(8) = struct(...
        'id', "PM Left Tip", ...
        'x', -3, 'y', 6, ...
        'mass', m_PM_node, 'inertia', I_PM_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

    struct_out.nodes(9) = struct(...
        'id', "PM Middle Left Tip", ...
        'x', -1.5, 'y', 6, ...
        'mass', m_PM_node, 'inertia', I_PM_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

  struct_out.nodes(10) = struct(...
        'id', "PM Middle Right Tip", ...
        'x', 1.5, 'y', 6, ...
        'mass', m_PM_node, 'inertia', I_PM_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);
     
      struct_out.nodes(11) = struct(...
        'id', "PM Right Tip", ...
        'x', 3, 'y', 6, ...
        'mass', m_PM_node, 'inertia', I_PM_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);

% Nodes: Camera: Cam
m_Cam_node = 1; I_Cam_node = 1;
    struct_out.nodes(12) = struct(...
        'id', "Camera Tip", ...
        'x', 0, 'y', 5, ...
        'mass', m_Cam_node, 'inertia', I_Cam_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0);
      
% Nodes: Isolators: Iso 
m_iso_node = 1; I_iso_node = 1; 
 struct_out.nodes(13) = struct(...
        'id', "Iso Beam Bottom Left", ...
        'x', -3, 'y', 3, ...
        'mass', m_iso_node, 'inertia', I_so_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0); 

    struct_out.nodes(14) = struct(...
        'id', "Iso Beam Middle Left", ...
        'x', -2.75, 'y', 3.75, ...
        'mass', m_iso_node, 'inertia', I_iso_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0); 

    struct_out.nodes(15) = struct(...
        'id', "Iso Beam Middle Right", ...
        'x', 2.75, 'y', 3.75, ...
        'mass', m_iso_node, 'inertia', I_iso_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0); 

    struct_out.nodes(16) = struct(...
        'id', "Iso Beam Bottom Right", ...
        'x', 3, 'y', 3, ...
        'mass', m_iso_node, 'inertia', I_iso_node, ...
        'constraints', [0, 0, 0], 'k_rot', 0); 

% nodes 13 and 15 might be repeats of nodes 2 and 4 of the bus, not sure if
% I keep or remove

    %% =====================================================================
    %  ELEMENT DEFINITIONS
    %  =====================================================================
    %  Each element requires the following fields:
    %  - id          : [String] Unique identifier for the element.
    %  - type        : [String] Element formulation type. 
    %                  Currently supported: "beam"
    %                  Future support   : "spring", "isolator"
    %  - nodes       : [1x2 String Array] Exact IDs of the connecting nodes.
    %  - E           : [Double] Young's Modulus in Pascals (Pa).
    %  - I           : [Double] Area Moment of Inertia in m^4.
    %  - A           : [Double] Cross-sectional area in m^2.
    %  - rho         : [Double] Mass density per unit length in kg/m.
    %  - k_discrete  : [Double] Stiffness in N/m (Used for discrete spring 
    %                  elements, ignored if type == "beam").

% Elements: Optical Bench: Obench
   E_Obench = 70e9; I_Obench = 0.09; A_Obench = 20; rho_Obench = 2700;
    struct_out.elements(1) = struct(...
        'id', "Obench Left", 'type', "beam", ...
        'nodes', ["Obench Far left", "Obench PM base left"], ... 
        'E', E_Obench, 'I', I_Obench, 'A', A_Obench, ...
        'rho', rho_Obench, 'k_discrete', 0);

    struct_out.elements(2) = struct(...
        'id', "Obench Middle Left", 'type', "beam", ...
        'nodes', ["Obench PM base left", "Obench PM base Middle left"], ... 
        'E', E_Obench, 'I', I_Obench, 'A', A_Obench, ...
        'rho', rho_Obench, 'k_discrete', 0);

    struct_out.elements(3) = struct(...
