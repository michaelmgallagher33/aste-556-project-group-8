 struct_out.elements(7) = struct(...
        'id', "PM Left", 'type', "beam", ...
        'nodes', ["Obench PM base left", "PM Left Tip"], ... 
        'E', E_PM, 'I', I_PM, 'A', A_PM, ...
        'rho', rho_PM, 'k_discrete', 0);

    struct_out.elements(8) = struct(...
        'id', "PM Middle Left", 'type', "beam", ...
        'nodes', ["Obench PM base Middle left", "PM Middle Left Tip"], ... 
        'E', E_PM, 'I', I_PM, 'A', A_PM, ...
        'rho', rho_PM, 'k_discrete', 0); 

     struct_out.elements(9) = struct(...
        'id', "PM Middle Right", 'type', "beam", ...
        'nodes', ["Obench PM base Middle Right", "PM Middle Right Tip"], ... 
        'E', E_PM, 'I', I_PM, 'A', A_PM, ...
        'rho', rho_PM, 'k_discrete', 0);

   struct_out.elements(10) = struct(...
        'id', "PM right", 'type', "beam", ...
        'nodes', ["Obench PM Base Right", "PM Right Tip"], ... 
        'E', E_PM, 'I', I_PM, 'A', A_PM, ...
        'rho', rho_PM, 'k_discrete', 0);

% Elements: Camera
 E_Cam = 70e9; I_Cam = 0.001; A_Cam = 0.05; rho_Cam = 2700;
   struct_out.elements(11) = struct(...
        'id', "Camera", 'type', "beam", ...
        'nodes', ["Obench Camera base", "Camera Tip"], ... 
        'E', E_Cam, 'I', I_Cam, 'A', A_Cam, ...
        'rho', rho_Cam, 'k_discrete', 0);

% Elements: Ioslator: Iso 
 E_Iso = 70e9; I_Iso = 0.09; A_Iso = 0.75; rho_Iso = 2700;
    struct_out.elements(12) = struct( ...
        'id', "Iso Bottom Left", 'type', "beam", ...
        'nodes', ["Iso Beam Bottom Left", "Iso Beam Middle Left"], ...
        'E', E_Iso, 'I', I_Iso, 'A', A_Iso, ...
        'rho', rho_Iso, 'k_discrete', 0);

    struct_out.elements(13) = struct( ...
        'id', "Iso Top Left", 'type', "beam", ...
        'nodes', ["Iso Beam Middle Left", "Obench PM base Middle left"], ...
        'E', E_Iso, 'I', I_Iso, 'A', A_Iso, ...
        'rho', rho_Iso, 'k_discrete', 0);

    struct_out.elements(14) = struct( ...
        'id', "Iso Bottom Right", 'type', "beam", ...
        'nodes', ["Iso Beam Bottom Right", "Iso Beam Middle Right"], ...
        'E', E_Iso, 'I', I_Iso, 'A', A_Iso, ...
